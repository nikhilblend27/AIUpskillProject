"""WriterAgent — summary.md -> polished newsletter.md (M4, final stage)."""

from __future__ import annotations

import logging
import re
from datetime import datetime
from pathlib import Path
from typing import Any

from src.agents.base_agent import BaseAgent

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = (
    "You write a concise, friendly daily AI/ML newsletter for software engineers. "
    "Only use facts and links present in the provided summary. Keep every source link."
)

WRITER_PROMPT = """Today's digest summary (markdown):

{summary}

Write the newsletter in markdown:
1. A short catchy intro (2-3 sentences) — no top-level "#" title, I add that.
2. One "## " section per topic, keeping the key points and linking sources as [title](url).
3. A one-paragraph "## TL;DR" at the end.
Professional but warm tone; emoji sparingly. Target 400-700 words."""


class WriterAgent(BaseAgent):
    def __init__(self, model: str | None = None, **kwargs: Any):
        super().__init__(model=model, **kwargs)

    async def _load_context(self, input_path: str) -> dict[str, Any]:
        return {"summary": Path(input_path).read_text(encoding="utf-8")}

    async def _process(self, context: dict[str, Any]) -> dict[str, Any]:
        summary = context["summary"]
        date = datetime.now().strftime("%Y-%m-%d")
        if "## " not in summary:  # nothing relevant today — don't spend an LLM call
            body = "Quiet day: no AI/ML stories cleared the relevance bar. See you tomorrow!"
        else:
            try:
                body = await self._call_llm(WRITER_PROMPT.format(summary=summary), SYSTEM_PROMPT)
                body = re.sub(r"^\s*# [^\n]*\n", "", body.strip())  # drop any H1 the model added
            except Exception as exc:  # noqa: BLE001 — ship the raw summary rather than nothing
                logger.warning("Newsletter generation failed: %s", exc)
                body = summary
        return {"newsletter": body, "date": date, "stats": {"words": len(body.split())}}

    async def _save_result(self, result: dict[str, Any], output_path: str) -> None:
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            f"# AI/ML Daily Newsletter — {result['date']}\n\n"
            f"{result['newsletter'].strip()}\n\n---\n\n"
            "*Generated by the AI Upskill multi-agent pipeline "
            f"(Filter → Summarize → Write, model: {self.model}).*\n",
            encoding="utf-8",
        )
